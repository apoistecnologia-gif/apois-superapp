import assert from 'node:assert/strict'
import {createServer as httpServer,request} from 'node:http'
import {createServer as httpsServer} from 'node:https'
import {readFileSync,mkdtempSync,rmSync} from 'node:fs'
import {tmpdir} from 'node:os'
import {join} from 'node:path'
import {randomBytes} from 'node:crypto'
import {createPrivateQuoteGateway} from './private-quote-gateway.mjs'
import {createQuoteSigner,quoteBody} from './quote-protocol.mjs'
import {createRemoteQuoteMetrics} from './remote-quote-metrics.mjs'
const actor='00000000-0000-4000-8000-000000000001',other='00000000-0000-4000-8000-000000000002'
const keys=[{keyId:'test-1',secret:randomBytes(32).toString('base64url')}]
const a={lat:-9.4,lng:-40.5},b={lat:-9.42,lng:-40.51},c={lat:-9.43,lng:-40.51}
let forwarded=0
const upstream=httpServer(async(req,res)=>{assert.equal(req.url,'/route');for await(const _ of req){};forwarded++;res.writeHead(200,{'content-type':'application/json'});res.end(JSON.stringify({code:'Ok',routes:[{distance:2100,duration:432}]}))})
const listen=(s,host='127.0.0.1')=>new Promise((ok,no)=>{s.once('error',no);s.listen(0,host,ok)})
const close=s=>{s.closeAllConnections();return new Promise(r=>s.close(r))}
const dir=mkdtempSync(join(tmpdir(),'apois-quote-tls-')),path=join(dir,'quote.sqlite')
let privateGateway,proxy
try{
 await listen(upstream)
 const start=async initialize=>{const g=await createPrivateQuoteGateway({keys,path,initialize,upstreamPort:upstream.address().port});await listen(g.server);return g}
 privateGateway=await start(true)
 proxy=httpsServer({key:readFileSync(process.argv[2]),cert:readFileSync(process.argv[3]),minVersion:'TLSv1.2'},(req,res)=>{
  if(req.url!=='/quote/route'||req.method!=='POST'){res.writeHead(404);res.end();return}
  const target=request({host:'127.0.0.1',port:privateGateway.server.address().port,path:'/route',method:'POST',headers:{'content-type':req.headers['content-type'],'content-length':req.headers['content-length'],...(req.headers.authorization?{authorization:req.headers.authorization}:{})}},up=>{res.writeHead(up.statusCode,up.headers);up.pipe(res)})
  target.on('error',()=>{res.writeHead(502);res.end()});req.pipe(target)
 })
 // localhost SAN certificate generated by CI; no TLS bypass or NODE_TLS_REJECT_UNAUTHORIZED.
 await listen(proxy,'localhost')
 const endpoint='https://localhost:'+proxy.address().port+'/quote/route'
 const signer=await createQuoteSigner({...keys[0],authUserId:actor})
 const body=quoteBody(a,b),token=await signer(body)
 const send=(authorization,value=body)=>fetch(endpoint,{method:'POST',redirect:'error',headers:{'content-type':'application/json',...(authorization?{authorization}:{})},body:JSON.stringify(value)})
 assert.equal((await send(null)).status,401)
 assert.equal((await send('Bearer fake')).status,401)
 assert.equal((await send(token,quoteBody(a,c))).status,403)
 assert.equal(forwarded,0)
 assert.equal((await send(token)).status,200);assert.equal(forwarded,1)
 assert.equal((await send(token)).status,403);assert.equal(forwarded,1)
 await privateGateway.close();privateGateway=await start(false)
 assert.equal((await send(token)).status,403);assert.equal(forwarded,1)
 const expired=await createQuoteSigner({...keys[0],authUserId:actor,now:()=>Date.now()-16000})
 assert.equal((await send(await expired(body))).status,403)
 const wrong=await createQuoteSigner({keyId:'test-1',secret:randomBytes(32).toString('base64url'),authUserId:actor})
 assert.equal((await send(await wrong(body))).status,403)
 const metrics=await createRemoteQuoteMetrics({endpoint,...keys[0],authUserId:other})
 assert.deepEqual(await metrics(a,b),{source:'OSM_VALHALLA_LAB',distanceKm:2.1,durationMin:7.2})
 assert.equal(forwarded,2)
 for(let n=0;n<5;n++)assert.ok(await metrics(a,b))
 assert.equal(await metrics(a,b),null)
 assert.equal(forwarded,7)
 await assert.rejects(()=>createRemoteQuoteMetrics({endpoint:'http://localhost/quote/route',...keys[0],authUserId:other}))
 await assert.rejects(()=>createRemoteQuoteMetrics({endpoint:'https://localhost/route',...keys[0],authUserId:other}))
 console.log('APOIS_PRIVATE_QUOTE_TLS_OK',JSON.stringify({tls:true,boundBody:true,replayAfterRestart:true,invalidKey:true,expired:true,perAccountLimit:true,forwarded}))
}finally{if(proxy)await close(proxy);if(privateGateway)await privateGateway.close();await close(upstream);rmSync(dir,{recursive:true,force:true})}
