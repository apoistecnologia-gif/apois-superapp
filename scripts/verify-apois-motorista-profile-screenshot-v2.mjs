// APOIS_MOTORISTA_SCREENSHOT_PROFILE_GATE_V2 — somente leitura, sem APK.
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { resolve } from "node:path";
const root=resolve(process.env.APOIS_MOTORISTA_WORKSPACE||".work/partner-motorista");
const read=(p)=>readFileSync(resolve(root,p),"utf8");
const uploader=read("src/components/ProfilePhotoUploader.tsx");
const profile=read("src/routes/motorista.perfil.tsx");
const photoService=read("src/lib/profilePhoto.ts");
assert.ok(uploader.includes("APOIS_DRIVER_PROFILE_ERROR_STAGE_V2"),"error-stage message missing");
assert.ok(uploader.includes("safe.has(message) ? message : fallback"),"raw server errors must not be displayed");
assert.ok(uploader.includes("Foto salva com sucesso, mas a visualização ainda não está disponível."),"saved vs display errors must be distinct");
assert.ok(uploader.includes("nativeDriverPicker && isNativeDriverPhotoPicker()"),"native photo picker must stay");
assert.ok(photoService.includes('upsert: false'),"no overwrite of other photos");
assert.ok(photoService.includes("const authUserId = await currentAuthUserId()"),"profile path must be owned by auth identity");
assert.ok(photoService.includes("await persistOwnProfilePhoto(path)"),"storage upload must link to own profile");
assert.ok(photoService.includes("createSignedUrl(path, SIGNED_URL_TTL_SECONDS)"),"private photo must use expiring signed link");
assert.ok(profile.includes("APOIS_DRIVER_REAL_RIDE_COUNT_V2"),"real ride count patch missing");
assert.ok(profile.includes('.select("id", { count: "exact", head: true })'),"actual ride count required");
assert.ok(profile.includes('.eq("driver_id", nextDriver.id)'),"count must be scoped to own driver");
assert.ok(profile.includes('.eq("status", "finalizada")'),"only finished rides");
assert.ok(profile.includes('setTotalRides(count ?? null)'),"no stale summary counter");
assert.ok(profile.includes('value={completed == null ? "—" : String(completed)}'),"unavailable value must not look like zero");
assert.ok(profile.includes('whitespace-nowrap text-center !text-[clamp('),"metric label cannot wrap");
assert.ok(profile.includes("Ver perfil público"),"public profile access preserved");
console.log("[OK] Motorista: photo stage errors, owner scope, real ride count and one-line ratings; no APK generated by this test.");
