import {readFileSync,writeFileSync} from 'node:fs';
import {resolve} from 'node:path';
const full=resolve('.work/corridas/src/routes/_public.cadastro.tsx');
let s=readFileSync(full,'utf8');
if(!s.includes('import { Capacitor } from "@capacitor/core";'))s='import { Capacitor } from "@capacitor/core";\n'+s;
const before='        options: {\n          data: {';
if(!s.includes(before))throw Error('[FAIL] Corridas cadastro: options ausentes');
s=s.replace(before,'        options: {\n          emailRedirectTo: Capacitor.isNativePlatform() ? "br.com.apois.app://auth/corridas-confirm" : new URL("/login", window.location.origin).toString(),\n          data: {');
if(!s.includes('br.com.apois.app://auth/corridas-confirm'))throw Error('[FAIL] Corridas: email confirmation redirect ausente');
writeFileSync(full,s,'utf8');
console.log('[OK] Cliente Corridas: confirmação de cadastro retorna ao app, sem fallback institucional.');
