import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {resolve} from "node:path";
const root=resolve(process.env.APOIS_ENTREGAS_WORKSPACE||".work/entregas");
const home=readFileSync(resolve(root,"src/routes/inicio.tsx"),"utf8");
const form=readFileSync(resolve(root,"src/routes/enderecos/novo.tsx"),"utf8");
const listing=readFileSync(resolve(root,"src/routes/enderecos.tsx"),"utf8");
assert.ok(home.includes("APOIS_ENTREGAS_AUTO_ADDRESS_CEP_V1"));
assert.ok(home.includes('if(isLoading || error || defaultAddress)return;'),"Nunca substituir endereco salvo");
assert.ok(home.includes("apois_auto_locate_new_address"),"GPS somente com formulario de confirmacao");
assert.ok(home.includes('navigate({ to: "/enderecos" })'),"Endereco clicavel preservado");
assert.ok(home.includes('is_default", true'),"Usar endereco padrao cadastrado");
assert.ok(form.includes("APOIS_ENTREGAS_CEP_LOOKUP_V1"));
assert.ok(form.includes("Buscar pelo CEP"));
assert.ok(form.includes("viacep.com.br/ws/"),"Busca por CEP original preservada");
assert.ok(form.includes("!hasPreciseLocation"),"Coordenadas obrigatorias antes de salvar");
assert.ok(form.includes("CustomerLocationAddressSelector"),"Google Places e GPS disponiveis");
assert.ok(listing.includes("set_default_customer_address")||listing.includes("setDefaultAddress"),"Mudanca manual do endereco deve ser persistida");
console.log("[OK] Enderecos Entregas: GPS quando necessario, endereco padrao, troca manual e CEP com confirmacao.");
