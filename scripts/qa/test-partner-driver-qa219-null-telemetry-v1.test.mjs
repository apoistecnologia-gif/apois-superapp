import test from "node:test";
import assert from "node:assert/strict";
import { readFileSync, existsSync } from "node:fs";
import { resolve } from "node:path";
import { patchNullTelemetry, marker } from "../fix-partner-driver-qa219-null-telemetry-v1.mjs";

// Keep a literal implementation fixture so the test is independent of production API calls.
const source = [
  "function normalizeHeading(value: number | null | undefined): number | null {",
  "  const heading = Number(value);",
  "  if (!Number.isFinite(heading)) return null;",
  "  return ((heading % 360) + 360) % 360;",
  "}",
  "",
  "function normalizeSpeed(value: number | null | undefined): number | null {",
  "  const speed = Number(value);",
  "  return Number.isFinite(speed) && speed >= 0 ? speed : null;",
  "}",
  "const payload = { driver_set_presence: true,",
  "  _online: publishOnline,",
  "  _heading: publishOnline ? normalizeHeading(position?.heading) : null,",
  "  _speed: publishOnline ? normalizeSpeed(position?.speed) : null,",
  "};",
].join("\n");

test("unknown GPS heading and speed stay null, real zero is retained", () => {
  const result = patchNullTelemetry(source);
  assert.ok(result.includes(marker));
  assert.ok(result.includes("if (value == null) return null;"));
  assert.equal(result.split("if (value == null) return null;").length - 1, 2);
  const headingSource = result.slice(result.indexOf("function normalizeHeading("), result.indexOf("\nfunction normalizeSpeed("))
    .replace(/: number \| null \| undefined/g, "").replace(/: number \| null/g,"");
  const speedSource = result.slice(result.indexOf("function normalizeSpeed("), result.indexOf("\nconst payload"))
    .replace(/: number \| null \| undefined/g, "").replace(/: number \| null/g,"");
  const evaluate = new Function(headingSource + "\n" + speedSource + "\nreturn {normalizeHeading,normalizeSpeed};")();
  for(const missing of [null,undefined]) {
    assert.equal(evaluate.normalizeHeading(missing),null);
    assert.equal(evaluate.normalizeSpeed(missing),null);
  }
  assert.equal(evaluate.normalizeHeading(0),0);
  assert.equal(evaluate.normalizeHeading(360),0);
  assert.equal(evaluate.normalizeHeading(270),270);
  assert.equal(evaluate.normalizeSpeed(0),0);
  assert.equal(evaluate.normalizeSpeed(12.5),12.5);
  assert.equal(evaluate.normalizeSpeed(-1),null);
  assert.equal(evaluate.normalizeSpeed(Number.NaN),null);
});
test("rejects repeated transforms and unexpected presence contracts",()=>{
  const result = patchNullTelemetry(source);
  assert.throws(()=>patchNullTelemetry(result),/already patched/);
  assert.throws(()=>patchNullTelemetry(source.replace("Number(value)","Number(heading)")),/unexpected GPS telemetry/);
  assert.throws(()=>patchNullTelemetry(source.replace("_online: publishOnline","_online: false")),/protected presence contract/);
});
test("source generated by build contains safe normalizers",()=>{
  const path=resolve(process.env.APOIS_MOTORISTA_WORKSPACE || ".work/partner-motorista", "src/hooks/useDriverBroadcast.ts");
  if(!existsSync(path))return;
  const generated=readFileSync(path,"utf8");
  assert.ok(generated.includes(marker));
  assert.ok(generated.includes("_heading: publishOnline ? normalizeHeading(position?.heading) : null"));
  assert.ok(generated.includes("_speed: publishOnline ? normalizeSpeed(position?.speed) : null"));
});
